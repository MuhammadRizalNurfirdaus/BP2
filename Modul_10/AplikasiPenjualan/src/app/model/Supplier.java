package app.model;

public class Supplier {
    private String kd_supplier;
    private String nama_supplier;
    private String nope_supplier;
    private String alamat;

    // --- Getters and Setters ---
    public String getKd_supplier() { return kd_supplier; }
    public void setKd_supplier(String kd_supplier) { this.kd_supplier = kd_supplier; }
    public String getNama_supplier() { return nama_supplier; }
    public void setNama_supplier(String nama_supplier) { this.nama_supplier = nama_supplier; }
    public String getNope_supplier() { return nope_supplier; }
    public void setNope_supplier(String nope_supplier) { this.nope_supplier = nope_supplier; }
    public String getAlamat() { return alamat; }
    public void setAlamat(String alamat) { this.alamat = alamat; }
}